import { getSupabase } from '@/lib/supabase/client';
import type { Database } from '@/types/database.types';
import type { ReportSubmissionInput } from '@/lib/validation/reports';

type ReportRow = Database['public']['Tables']['reports']['Row'];
type ReportMediaRow = Database['public']['Tables']['report_media']['Row'];
type ReportStatusHistoryRow = Database['public']['Tables']['report_status_history']['Row'];

export interface ReportDetailWithMedia extends ReportRow {
  media: (ReportMediaRow & { signedUrl?: string | null })[];
  history: ReportStatusHistoryRow[];
}

export interface SubmitReportResult {
  report: ReportRow;
  mediaCount: number;
  uploadedPaths: string[];
}

/**
 * Generates a temporary signed URL for viewing private evidence photos stored in the
 * private 'report-evidence' or 'resolution-evidence' Supabase bucket.
 */
export async function getSignedMediaUrl(
  bucket: 'report-evidence' | 'resolution-evidence',
  storagePath: string,
  expiresInSeconds: number = 3600
): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return null;

  try {
    const { data, error } = await supabase.storage
      .from(bucket)
      .createSignedUrl(storagePath, expiresInSeconds);

    if (error || !data?.signedUrl) {
      console.warn(`Failed to create signed URL for ${storagePath}:`, error?.message);
      return null;
    }

    return data.signedUrl;
  } catch (err) {
    console.error('Error generating signed media URL:', err);
    return null;
  }
}

/**
 * Submits a new cleanliness complaint with atomic rollback of storage files
 * in case of network or database failures.
 */
export async function submitCitizenReport(
  input: ReportSubmissionInput,
  photos: File[],
  authenticatedUserId: string,
  onProgress?: (step: 'inserting_report' | 'uploading_photos' | 'linking_media' | 'completed') => void
): Promise<SubmitReportResult> {
  const supabase = getSupabase();
  if (!supabase) {
    throw new Error('Supabase client is not configured.');
  }

  onProgress?.('inserting_report');

  // 1. Insert the report record into public.reports
  // Note: complaint_id is generated by PostgreSQL sequence trigger trg_generate_complaint_id
  const { data: newReport, error: reportError } = await supabase
    .from('reports')
    .insert([
      {
        reporter_id: authenticatedUserId,
        category: input.category,
        priority: input.priority || 'medium',
        description: input.description.trim(),
        ward_number: input.ward_number || null,
        address_locality: input.address_locality?.trim() || null,
        landmark: input.landmark?.trim() || null,
        latitude: input.latitude || null,
        longitude: input.longitude || null,
        is_anonymous: input.is_anonymous || false,
        status: 'submitted',
      },
    ])
    .select('*')
    .single();

  if (reportError || !newReport) {
    throw new Error(reportError?.message || 'Failed to register complaint in database.');
  }

  const uploadedPaths: string[] = [];

  // If there are photos, upload them to the private report-evidence bucket
  if (photos.length > 0) {
    onProgress?.('uploading_photos');

    try {
      for (const file of photos) {
        // Path convention: {user_id}/{report_id}/{unique_filename}
        const safeName = file.name.replace(/[^a-zA-Z0-9.-]/g, '_');
        const uniqueId = crypto.randomUUID ? crypto.randomUUID() : Math.random().toString(36).substring(2);
        const storagePath = `${authenticatedUserId}/${newReport.id}/${uniqueId}-${safeName}`;

        const { error: uploadError } = await supabase.storage
          .from('report-evidence')
          .upload(storagePath, file, {
            contentType: file.type,
            upsert: false,
          });

        if (uploadError) {
          throw new Error(`Photo upload failed: ${uploadError.message}`);
        }

        uploadedPaths.push(storagePath);
      }

      onProgress?.('linking_media');

      // Link uploaded media metadata to report_media table
      const mediaRecords = uploadedPaths.map((path, idx) => {
        const file = photos[idx];
        return {
          report_id: newReport.id,
          storage_path: path,
          file_size_bytes: file?.size || 0,
          mime_type: file?.type || 'image/jpeg',
          media_type: 'initial_evidence',
          uploaded_by: authenticatedUserId,
        };
      });

      const { error: mediaInsertError } = await supabase
        .from('report_media')
        .insert(mediaRecords);

      if (mediaInsertError) {
        throw new Error(`Failed to associate media with complaint: ${mediaInsertError.message}`);
      }
    } catch (uploadOrLinkError) {
      // Rollback: Clean up any files that were uploaded to prevent orphaned storage objects
      if (uploadedPaths.length > 0) {
        console.warn('Rolling back uploaded storage objects due to failure:', uploadedPaths);
        await supabase.storage.from('report-evidence').remove(uploadedPaths);
      }
      throw uploadOrLinkError;
    }
  }

  onProgress?.('completed');
  return {
    report: newReport,
    mediaCount: uploadedPaths.length,
    uploadedPaths,
  };
}

/**
 * Fetches all reports submitted by the authenticated citizen.
 */
export async function getCitizenReports(
  userId: string
): Promise<(ReportRow & { mediaThumbUrl?: string | null })[]> {
  const supabase = getSupabase();
  if (!supabase) return [];

  const { data: reports, error } = await supabase
    .from('reports')
    .select('*, report_media(storage_path)')
    .eq('reporter_id', userId)
    .order('submitted_at', { ascending: false });

  if (error || !reports) {
    throw new Error(error?.message || 'Failed to fetch your reports.');
  }

  // Populate first photo thumbnail signed URL for each report
  const enrichedReports = await Promise.all(
    reports.map(async (rep) => {
      let mediaThumbUrl: string | null = null;
      // @ts-expect-error Supabase join type inference
      const mediaList = rep.report_media as { storage_path: string }[] | undefined;
      const firstPath = mediaList?.[0]?.storage_path;

      if (firstPath) {
        mediaThumbUrl = await getSignedMediaUrl('report-evidence', firstPath, 1800);
      }

      return {
        ...rep,
        mediaThumbUrl,
      };
    })
  );

  return enrichedReports;
}

/**
 * Fetches detailed complaint information including media and status history trail.
 * Queryable by UUID or Complaint Reference (e.g. NAV-2026-00101).
 */
export async function getReportDetailWithMedia(
  identifier: string
): Promise<ReportDetailWithMedia | null> {
  const supabase = getSupabase();
  if (!supabase) return null;

  // Determine whether identifier is a UUID or a complaint_id
  const isUuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
    identifier
  );

  const query = supabase
    .from('reports')
    .select('*, report_media(*), report_status_history(*)');

  const { data, error } = isUuid
    ? await query.eq('id', identifier).maybeSingle()
    : await query.eq('complaint_id', identifier.toUpperCase().trim()).maybeSingle();

  if (error) {
    throw new Error(error.message);
  }

  if (!data) {
    return null;
  }

  // Generate signed URLs for all associated media
  // @ts-expect-error Supabase relation array type
  const rawMedia = (data.report_media as ReportMediaRow[]) || [];
  const mediaWithSignedUrls = await Promise.all(
    rawMedia.map(async (m) => {
      const signedUrl = await getSignedMediaUrl('report-evidence', m.storage_path, 3600);
      return {
        ...m,
        signedUrl,
      };
    })
  );

  // @ts-expect-error Supabase relation array type
  const history = ((data.report_status_history as ReportStatusHistoryRow[]) || []).sort(
    (a, b) => new Date(a.created_at).getTime() - new Date(b.created_at).getTime()
  );

  return {
    ...data,
    media: mediaWithSignedUrls,
    history,
  };
}
